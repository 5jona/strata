//! Static ARM64/GKI-safe catalog items and known APT inventory packages.

use strata_protocol::rpc::{ToolGroupKind, ToolManagerKind};

pub(super) struct StaticCatalogItem {
    pub(super) id: &'static str,
    pub(super) name: &'static str,
    pub(super) summary: &'static str,
    pub(super) manager: ToolManagerKind,
    pub(super) group: ToolGroupKind,
    pub(super) default_version: &'static str,
    pub(super) backend_hint: &'static str,
    pub(super) estimated_mb: u32,
    pub(super) recommended: bool,
    pub(super) tags: &'static [&'static str],
}

#[allow(clippy::too_many_arguments)]
const fn item(
    id: &'static str,
    name: &'static str,
    summary: &'static str,
    manager: ToolManagerKind,
    group: ToolGroupKind,
    default_version: &'static str,
    backend_hint: &'static str,
    estimated_mb: u32,
    recommended: bool,
    tags: &'static [&'static str],
) -> StaticCatalogItem {
    StaticCatalogItem {
        id,
        name,
        summary,
        manager,
        group,
        default_version,
        backend_hint,
        estimated_mb,
        recommended,
        tags,
    }
}

